import "server-only";
import { randomBytes, randomUUID } from "node:crypto";
import { copyFile, mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { hashPassword } from "@/lib/auth/password";
import { normalizeRequirements } from "@/lib/domain/requirements";
import { SAMPLE_CERTIFICATES } from "@/lib/domain/extraction/samples";
import { DEMO_EMAIL, DEMO_PASSWORD, buildDemoDatabase } from "@/lib/seed";
import type {
  CertificateRecord,
  ContractorRecord,
  Database,
  NewCertificate,
  NewContractor,
  NewSubcontractor,
  OutboxRecord,
  PaymentRecord,
  ReminderRecord,
  Store,
  StoredBlob,
  SubcontractorRecord,
} from "@/lib/store/types";

const root = path.join(process.cwd(), ".data");
const dbFile = path.join(root, "db.json");
const blobDir = path.join(root, "blobs");

let queue: Promise<unknown> = Promise.resolve();

function withLock<T>(fn: () => Promise<T>): Promise<T> {
  const run = queue.then(fn, fn);
  queue = run.then(
    () => undefined,
    () => undefined,
  );
  return run;
}

async function readDb(): Promise<Database> {
  await mkdir(root, { recursive: true });
  try {
    const raw = await readFile(dbFile, "utf8");
    const parsed = JSON.parse(raw) as Database;
    parsed.contractors = parsed.contractors.map((contractor) => ({
      ...contractor,
      requirements: normalizeRequirements(contractor.requirements),
    }));
    return parsed;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    const seeded = buildDemoDatabase(hashPassword(DEMO_PASSWORD));
    await writeDb(seeded);
    return seeded;
  }
}

async function writeDb(db: Database) {
  await mkdir(root, { recursive: true });
  const tmp = path.join(root, `db.${process.pid}.tmp`);
  await writeFile(tmp, JSON.stringify(db));
  await rename(tmp, dbFile);
}

async function ensureSampleBlobs() {
  await mkdir(blobDir, { recursive: true });
  for (const spec of SAMPLE_CERTIFICATES) {
    const dest = path.join(blobDir, `seed-${spec.key}`);
    try {
      await stat(dest);
      continue;
    } catch {
      // copy when the sample exists and the blob does not
    }
    const src = path.join(process.cwd(), "samples", spec.filename);
    try {
      await copyFile(src, dest);
    } catch {
      // Samples are generated by scripts/generate-samples.ts. The record still loads.
    }
  }
}

function token() {
  return randomBytes(18).toString("base64url");
}

export class LocalStore implements Store {
  private ready: Promise<void> | null = null;

  private prepare() {
    this.ready ??= ensureSampleBlobs();
    return this.ready;
  }

  async reset() {
    await withLock(async () => {
      await rm(root, { recursive: true, force: true });
      this.ready = null;
      await this.prepare();
      await readDb();
    });
  }

  findContractorById(id: string) {
    return this.one((db) => db.contractors.find((row) => row.id === id) ?? null);
  }
  findContractorByEmail(email: string) {
    const needle = email.trim().toLowerCase();
    return this.one((db) => db.contractors.find((row) => row.email.toLowerCase() === needle) ?? null);
  }
  findContractorByAuthUserId(authUserId: string) {
    return this.one((db) => db.contractors.find((row) => row.authUserId === authUserId) ?? null);
  }
  findContractorByStripeCustomer(customerId: string) {
    return this.one(
      (db) => db.contractors.find((row) => row.stripeCustomerId === customerId) ?? null,
    );
  }
  listContractors() {
    return this.one((db) => db.contractors);
  }

  createContractor(input: NewContractor) {
    return this.change((db) => {
      if (db.contractors.some((row) => row.email.toLowerCase() === input.email.toLowerCase())) {
        throw new Error("An account with that email already exists.");
      }
      const row: ContractorRecord = {
        id: randomUUID(),
        authUserId: input.authUserId ?? null,
        email: input.email.trim().toLowerCase(),
        passwordHash: input.passwordHash,
        contactName: input.contactName.trim(),
        companyName: input.companyName.trim(),
        address1: "",
        city: "",
        state: "",
        postalCode: "",
        plan: "free",
        subscriptionStatus: input.subscriptionStatus ?? "trialing",
        trialEndsAt: input.trialEndsAt,
        stripeCustomerId: null,
        stripeSubscriptionId: null,
        auditRescuePurchasedAt: null,
        requirements: normalizeRequirements({}),
        createdAt: new Date().toISOString(),
      };
      db.contractors.push(row);
      return row;
    });
  }

  updateContractor(id: string, patch: Partial<Omit<ContractorRecord, "id" | "email" | "createdAt">>) {
    return this.change((db) => {
      const row = db.contractors.find((item) => item.id === id);
      if (!row) throw new Error("Account not found.");
      if (patch.requirements) patch.requirements = normalizeRequirements(patch.requirements);
      Object.assign(row, patch);
      return row;
    });
  }

  listSubs(contractorId: string) {
    return this.one((db) =>
      db.subcontractors
        .filter((row) => row.contractorId === contractorId)
        .sort((a, b) => a.name.localeCompare(b.name)),
    );
  }

  createSubs(inputs: NewSubcontractor[]) {
    return this.change((db) => {
      const created: SubcontractorRecord[] = inputs.map((input) => ({
        id: randomUUID(),
        contractorId: input.contractorId,
        name: input.name.trim(),
        email: input.email?.trim() ?? "",
        phone: input.phone?.trim() ?? "",
        trade: input.trade?.trim() ?? "",
        agentName: input.agentName?.trim() ?? "",
        agentEmail: input.agentEmail?.trim() ?? "",
        uploadToken: token(),
        createdAt: new Date().toISOString(),
      }));
      db.subcontractors.push(...created);
      return created;
    });
  }

  getSub(contractorId: string, id: string) {
    return this.one(
      (db) => db.subcontractors.find((row) => row.contractorId === contractorId && row.id === id) ?? null,
    );
  }

  getSubByToken(uploadToken: string) {
    return this.one((db) => db.subcontractors.find((row) => row.uploadToken === uploadToken) ?? null);
  }

  updateSub(
    contractorId: string,
    id: string,
    patch: Partial<Pick<SubcontractorRecord, "name" | "email" | "phone" | "trade" | "agentName" | "agentEmail">>,
  ) {
    return this.change((db) => {
      const row = db.subcontractors.find((item) => item.contractorId === contractorId && item.id === id);
      if (!row) throw new Error("Subcontractor not found.");
      Object.assign(row, patch);
      return row;
    });
  }

  deleteSub(contractorId: string, id: string) {
    return this.change((db) => {
      db.subcontractors = db.subcontractors.filter(
        (row) => !(row.contractorId === contractorId && row.id === id),
      );
      db.certificates = db.certificates.filter(
        (row) => !(row.contractorId === contractorId && row.subcontractorId === id),
      );
    });
  }

  listCertificates(contractorId: string, subcontractorId?: string) {
    return this.one((db) =>
      db.certificates
        .filter(
          (row) =>
            row.contractorId === contractorId &&
            (subcontractorId ? row.subcontractorId === subcontractorId : true),
        )
        .sort((a, b) => b.uploadedAt.localeCompare(a.uploadedAt)),
    );
  }

  getCertificate(contractorId: string, id: string) {
    return this.one(
      (db) => db.certificates.find((row) => row.contractorId === contractorId && row.id === id) ?? null,
    );
  }

  addCertificate(input: NewCertificate) {
    return this.change((db) => {
      const row: CertificateRecord = {
        id: randomUUID(),
        contractorId: input.contractorId,
        subcontractorId: input.subcontractorId,
        blobId: input.blobId,
        filename: input.filename,
        mimeType: input.mimeType,
        byteSize: input.byteSize,
        status: "pending_review",
        extraction: input.extraction,
        confirmed: null,
        uploadedAt: new Date().toISOString(),
        confirmedAt: null,
      };
      db.certificates.push(row);
      return row;
    });
  }

  updateCertificate(
    contractorId: string,
    id: string,
    patch: Partial<Pick<CertificateRecord, "status" | "confirmed" | "confirmedAt" | "extraction">>,
  ) {
    return this.change((db) => {
      const row = db.certificates.find((item) => item.contractorId === contractorId && item.id === id);
      if (!row) throw new Error("Certificate not found.");
      Object.assign(row, patch);
      return row;
    });
  }

  replacePayments(contractorId: string, rows: Omit<PaymentRecord, "id" | "contractorId" | "importedAt">[]) {
    return this.change((db) => {
      db.payments = db.payments.filter((row) => row.contractorId !== contractorId);
      const importedAt = new Date().toISOString();
      const created = rows.map((row) => ({
        ...row,
        id: randomUUID(),
        contractorId,
        importedAt,
      }));
      db.payments.push(...created);
      return created;
    });
  }

  listPayments(contractorId: string) {
    return this.one((db) =>
      db.payments
        .filter((row) => row.contractorId === contractorId)
        .sort((a, b) => a.paidOn.localeCompare(b.paidOn)),
    );
  }

  listReminders(contractorId: string) {
    return this.one((db) => db.reminders.filter((row) => row.contractorId === contractorId));
  }

  addReminder(input: Omit<ReminderRecord, "id" | "sentAt"> & { sentAt?: string }) {
    return this.change((db) => {
      const row: ReminderRecord = {
        ...input,
        id: randomUUID(),
        sentAt: input.sentAt ?? new Date().toISOString(),
      };
      db.reminders.push(row);
      return row;
    });
  }

  addOutbox(input: Omit<OutboxRecord, "id" | "createdAt">) {
    return this.change((db) => {
      const row: OutboxRecord = { ...input, id: randomUUID(), createdAt: new Date().toISOString() };
      db.outbox.unshift(row);
      return row;
    });
  }

  listOutbox(contractorId: string) {
    return this.one((db) => db.outbox.filter((row) => row.contractorId === contractorId));
  }

  addLead(input: { email: string; source: string; summary: unknown }) {
    return this.change((db) => {
      db.leads.push({
        id: randomUUID(),
        email: input.email,
        source: input.source,
        summary: input.summary,
        createdAt: new Date().toISOString(),
      });
    });
  }

  async putBlob(blobId: string, bytes: Buffer, meta: { mimeType: string; filename: string }) {
    void meta.filename;
    const dest = path.join(blobDir, blobId);
    await mkdir(path.dirname(dest), { recursive: true });
    await writeFile(dest, bytes);
  }

  async getBlob(blobId: string): Promise<StoredBlob | null> {
    await this.prepare();
    try {
      const bytes = await readFile(path.join(blobDir, blobId));
      const db = await readDb();
      const cert = db.certificates.find((row) => row.blobId === blobId);
      return {
        bytes,
        mimeType: cert?.mimeType || "application/octet-stream",
        filename: cert?.filename || "certificate",
      };
    } catch {
      return null;
    }
  }

  private one<T>(fn: (db: Database) => T): Promise<T> {
    return withLock(async () => {
      await this.prepare();
      return fn(await readDb());
    });
  }

  private change<T>(fn: (db: Database) => T): Promise<T> {
    return withLock(async () => {
      await this.prepare();
      const db = await readDb();
      const result = fn(db);
      await writeDb(db);
      return result;
    });
  }
}

export async function resetLocalDemo() {
  await new LocalStore().reset();
}

export function isDemoEmail(email: string) {
  return email.toLowerCase() === DEMO_EMAIL;
}
